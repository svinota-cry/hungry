function deriveTags(kcal: number, cat: Cat): FoodTag[] {
  const tags: FoodTag[] = [];
  if (cat === "drink") tags.push("liquid");
  if (kcal <= 70 && cat !== "sweet") tags.push("safe");
  if (kcal >= 400 || (cat === "sweet" && kcal >= 300)) tags.push("red");
  return tags;
}

