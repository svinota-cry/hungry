export function statusLine(ratio: number): string {
  if (ratio <= 0) return "Пустота. Она тоже калорийна.";
  if (ratio < 0.25) return "Ещё держишься. Пока.";
  if (ratio < 0.55) return "Половина пути. Или половина ямы.";
  if (ratio < 0.85) return "Почти. Как всегда.";
  if (ratio < 1) return "На границе. Дыши.";
  if (ratio < 1.2) return "Ну вот. Теперь ты официально человек.";
  return "Перебор. Мир не закончился. Правда.";
}

export function pick<T>(arr: readonly T[], seed: number): T {
  return arr[Math.abs(seed) % arr.length];
}
